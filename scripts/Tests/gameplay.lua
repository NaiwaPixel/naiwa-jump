local V=assert(rawget(_G,"V"),"Official validation harness required")
V.assert(NaiwaJump~=nil,"game entry exports validation handle")
V.assert(require("urhox-libs/UI").GetRoot()~=nil,"actual UI root exists")
require("Tests.Rules").run(function(condition,message) V.assert(condition,message) end)
require("Tests.Rewards").run(function(condition,message) V.assert(condition,message) end)
require("Tests.Leaderboard").run(function(condition,message) V.assert(condition,message) end)
NaiwaJump.start()
V.atFrame(40,function()
 V.assert(NaiwaJump.run.phase=="ready","actual start action creates a ready game")
 NaiwaJump.run:press("acceptance")
end)
V.atFrame(70,function() NaiwaJump.run:release("acceptance") end)
V.atFrame(160,function()
 V.assert(NaiwaJump.run.phase~="flight","real loop resolves a jump")
 NaiwaJump.start()
end)
V.atFrame(180,function()
 V.assert(NaiwaJump.run.phase=="ready","real restart presents playable HUD")
end)
